"""Generates templeos/StAnna.HC (HolyC) from src/game.c + templeos/platform.HC.

game.c is written in a HolyC-compatible subset of C, so the translation is
mostly mechanical: drop the C-only include block, paste game_data.inc in at
its marker, keep the #defines from game.h, turn the CH string type into U8
and spell the umlauts as ASCII (TempleOS uses its own 8-bit character set).
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
header = (root / "src/game.h").read_text(encoding="utf-8")
core = (root / "src/game.c").read_text(encoding="utf-8")
data = (root / "src/game_data.inc").read_text(encoding="utf-8")
platform = (root / "templeos/platform.HC").read_text(encoding="utf-8")

defines = [line for line in header.splitlines()
           if line.startswith("#define") and not re.match(r"#define (TRUE|FALSE|STANNA_GAME_H)\b", line)]

core = re.sub(r"/\*C_ONLY\*/.*?/\*END_C_ONLY\*/\n", "", core, flags=re.S)
marker = "/*HOLYC_INCLUDE game_data.inc*/"
if marker not in core:
    raise SystemExit("game.c lost its HOLYC_INCLUDE marker")
core = core.replace(marker, data)
core = re.sub(r"\bCH\b", "U8", core)

umlauts = {"Ä": "AE", "Ö": "OE", "Ü": "UE", "ä": "ae", "ö": "oe", "ü": "ue", "ß": "SS"}

prelude = f"""// St. Anna Schule - "Herr Thuener kommt" - TempleOS port (HolyC)
// GENERATED by tools/make_holyc.py from src/game.c - edit those, not this.
//
// Copy this file into TempleOS (e.g. via a RedSea/FAT disk image) and run
//   #include "StAnna.HC";
// Keys: arrows/WASD walk, Shift run, E/space action (hide, talk, use),
// Q/F phone, Enter start, Esc back. Music and effects: PC speaker.

{chr(10).join(defines)}

// sound requests from the game core, played by SaSndUpdate below
I64 sa_snd_t = 0;
I64 sa_snd_id = 0;

U0 SaPlatSound(I64 id)
{{
  sa_snd_id = id;
  sa_snd_t = 0;
}}
"""

out = prelude + "\n" + core + "\n" + platform
for k, v in umlauts.items():
    out = out.replace(k, v)
if "$" in out:
    raise SystemExit("'$' would start a DolDoc command in TempleOS")
bad = sorted({c for c in out if ord(c) > 126})
if bad:
    raise SystemExit(f"non-ASCII characters left: {bad}")
# constructs HolyC lacks, searched in the code with comments and strings blanked
code = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), core, flags=re.S)
code = re.sub(r'"(\\.|[^"\\])*"', '""', code)
code = re.sub(r"'(\\.|[^'\\])'", "0", code)
for word in (r"\bstatic\b", r"\bconst\b", r"\bcontinue\b", r"\?", r"\bstruct\b", r"\btypedef\b",
             r"\benum\b", r"\bunsigned\b", r"\(\s*(int|char|U8|I64|U32)\s*\*?\s*\)"):
    m = re.search(word, code)
    if m:
        line = code[:m.start()].count("\n") + 1
        raise SystemExit(f"C-only construct {word!r} at game.c line {line}: {core.splitlines()[line - 1].strip()}")

dst = root / "templeos/StAnna.HC"
dst.write_bytes(out.replace("\r\n", "\n").encode("ascii"))
print(f"wrote {dst} ({len(out.splitlines())} lines)")
